package dto;

public class AtributoDTO {
    private String idAtributo;
    private String nomeAtributo;
    private String valor;

    // Getters e Setters
    public String getIdAtributo() { return idAtributo; }
    public void setIdAtributo(String idAtributo) { this.idAtributo = idAtributo; }

    public String getNomeAtributo() { return nomeAtributo; }
    public void setNomeAtributo(String nomeAtributo) { this.nomeAtributo = nomeAtributo; }

    public String getValor() { return valor; }
    public void setValor(String valor) { this.valor = valor; }
}